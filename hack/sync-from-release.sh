#!/usr/bin/env bash
#
# Regenerates charts/console-operator/{crds,templates}/*.yaml from the
# "non-OLM install" manifest that streamshub/console attaches to every
# GitHub release (operator/controller/bin/generate-non-olm-install.sh
# upstream). This keeps the chart a low-drift mirror of what upstream itself
# considers the canonical plain-Kubernetes install for a given release,
# instead of a hand-maintained copy that can silently fall out of sync.
#
# Usage: hack/sync-from-release.sh [VERSION]
#   VERSION defaults to the latest streamshub/console GitHub release tag.
#
# Only a few values are templated (image, watched namespaces, pull policy,
# replica count, two optional-resource gates) — see values.yaml for why.
# Everything else (RBAC rules, probes, resource requests, labels) is left
# exactly as upstream generates it.
set -euo pipefail

UPSTREAM_REPO="streamshub/console"
ASSET_NAME="streamshub-console-operator.yaml"
CHART_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/charts/console-operator"
GENERATED_MARKER="# AUTO-GENERATED by hack/sync-from-release.sh from the ${UPSTREAM_REPO} release manifest. Do not hand-edit; re-run the script instead."

VERSION="${1:-}"
if [[ -z "${VERSION}" ]]; then
  VERSION="$(gh api "repos/${UPSTREAM_REPO}/releases/latest" --jq .tag_name)"
fi

echo "Syncing console-operator chart from ${UPSTREAM_REPO}@${VERSION}"

WORKDIR="$(mktemp -d)"
trap 'rm -rf "${WORKDIR}"' EXIT

gh release download "${VERSION}" --repo "${UPSTREAM_REPO}" \
  --pattern "${ASSET_NAME}" --dir "${WORKDIR}" --clobber

MANIFEST="${WORKDIR}/${ASSET_NAME}"

# Split the multi-document manifest into one raw file per document, preserving
# exact original text (no YAML re-serialization, to avoid altering the huge
# CRD schema's formatting/semantics).
awk -v dir="${WORKDIR}" '
  BEGIN { n = 0; file = sprintf("%s/doc-%03d.yaml", dir, n) }
  /^---[[:space:]]*$/ { n++; file = sprintf("%s/doc-%03d.yaml", dir, n); next }
  { print > file }
' "${MANIFEST}"

# Clear out only previously generated files, never hand-authored ones
# (_helpers.tpl, NOTES.txt, values.schema.json, etc.).
for f in "${CHART_DIR}"/crds/*.yaml "${CHART_DIR}"/templates/*.yaml; do
  [[ -f "$f" ]] || continue
  if grep -qF "AUTO-GENERATED by hack/sync-from-release.sh" "$f"; then
    rm -f "$f"
  fi
done

slugify() {
  # lowercase, strip common noisy prefixes, replace non-alnum with '-'
  echo "$1" \
    | tr '[:upper:]' '[:lower:]' \
    | sed -E 's/^streamshub-consolereconciler-//; s/^streamshub-console-//; s/^streamshub-//' \
    | sed -E 's/[^a-z0-9]+/-/g; s/^-+|-+$//g'
}

for doc in "${WORKDIR}"/doc-*.yaml; do
  [[ -s "$doc" ]] || continue
  kind="$(yq -r 'select(.kind != null) | .kind' "$doc" | head -1)"
  [[ -n "$kind" && "$kind" != "null" ]] || continue
  name="$(yq -r '.metadata.name' "$doc")"
  roleRefName="$(yq -r '.roleRef.name // ""' "$doc")"

  if [[ "$kind" == "CustomResourceDefinition" ]]; then
    { echo "${GENERATED_MARKER}"; cat "$doc"; } > "${CHART_DIR}/crds/${name}.yaml"
    echo "  crds/${name}.yaml  (verbatim content, no templating)"
    continue
  fi

  slug="$(slugify "${name}")"
  kindSlug="$(slugify "${kind}")"
  outfile="${CHART_DIR}/templates/${kindSlug}-${slug}.yaml"

  {
    echo "${GENERATED_MARKER}"
    cat "$doc"
  } \
    | sed -E 's#namespace: "\$\{NAMESPACE\}"#namespace: {{ .Release.Namespace }}#' \
    | sed -E 's#image: quay\.io/streamshub/console-operator:[^[:space:]]+#image: "{{ include "console-operator.image" . }}"#' \
    | sed -E 's#imagePullPolicy: Always#imagePullPolicy: {{ .Values.image.pullPolicy }}#' \
    | sed -E 's#^([[:space:]]*)replicas: 1[[:space:]]*$#\1replicas: {{ .Values.replicaCount }}#' \
    | sed -E 's#^([[:space:]]*)value: JOSDK_ALL_NAMESPACES[[:space:]]*$#\1value: {{ .Values.watchNamespaces | quote }}#' \
    > "${outfile}"

  if [[ "$kind" == "ServiceMonitor" ]]; then
    { echo "{{- if .Values.serviceMonitor.enabled }}"; cat "${outfile}"; echo "{{- end }}"; } > "${outfile}.tmp"
    mv "${outfile}.tmp" "${outfile}"
  elif [[ "$kind" == "ClusterRoleBinding" && "$roleRefName" == "cluster-monitoring-view" ]]; then
    { echo "{{- if .Values.openshift.clusterMonitoringView }}"; cat "${outfile}"; echo "{{- end }}"; } > "${outfile}.tmp"
    mv "${outfile}.tmp" "${outfile}"
  fi

  echo "  templates/$(basename "${outfile}")  (from ${kind} ${name})"
done

yq -i ".version = \"${VERSION#v}\" | .appVersion = \"${VERSION#v}\"" "${CHART_DIR}/Chart.yaml"

echo "Synced chart to version ${VERSION#v}."
